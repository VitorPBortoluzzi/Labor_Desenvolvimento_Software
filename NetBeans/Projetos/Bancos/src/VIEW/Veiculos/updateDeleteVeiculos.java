    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Veiculos v = new Veiculos();
        v.setId(Integer.parseInt(txtF_id.getText()));
        v.setModelo(txtF_modelo.getText());
        v.setPlaca(txtF_placa.getText());
        v.setPessoaid((Pessoa) cmb_pessoas.getSelectedItem());
        
        VeiculosDAO vdao = new VeiculosDAO();
        vdao.editar(v);
        limparFormulario();
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int idVeiculo = Integer.parseInt(txtF_id.getText());
        VeiculosDAO vDAO = new VeiculosDAO();
        
        Veiculos v = vDAO.getVeiculo(idVeiculo);
        
        if( v ==null){
            limparFormulario();
            JOptionPane.showMessageDialog(this, "Veiculo não encontrado");
        } else {
            txtF_id.setText(idVeiculo + "");
            txtF_modelo.setText(v.getModelo());
            txtF_placa.setText(v.getPlaca());
            
            Pessoa pessoaSelecionada = (Pessoa) v.getPessoaid();
            cmb_pessoas.setSelectedItem(pessoaSelecionada);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

