    public void preencherComboPessoas(){
        PessoaDAO pDAO = new PessoaDAO();
        List<Pessoa> listaP = pDAO.getPessoas();
        for(Pessoa p: listaP){
            cmb_pessoa.addItem(p);
        }
    }
    
