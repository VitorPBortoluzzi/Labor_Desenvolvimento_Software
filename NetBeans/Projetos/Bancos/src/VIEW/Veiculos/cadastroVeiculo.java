    private void btn_cadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cadastrarActionPerformed
        Veiculos v = new Veiculos();

        if (txtF_modelo.getText().isBlank()) {
            System.err.println("Modelo não inserido");
            return;
        }
        v.setModelo(txtF_modelo.getText());

        if (txtF_placa.getText().isBlank()) {
            System.err.println("Placa não inserida");
            return;
        }
        v.setPlaca(txtF_placa.getText());

        Object selecionado = cmb_pessoa.getSelectedItem();
        if (!(selecionado instanceof Pessoa)) {
            System.err.println("Pessoa não selecionada");
            return;
        }
        v.setPessoaid((Pessoa) selecionado);

        try {
            vdao.inserir(v);
            limparFormulario();
        } catch (Exception e) {
            System.out.println(e + "\nVeículo não inserido");
        }
    }//GEN-LAST:event_btn_cadastrarActionPerformed

